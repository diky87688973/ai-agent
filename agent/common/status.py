def require(value: Any, allowed: Iterable[str], what: str = "状态") -> str:
    """校验状态值并返回；未知值直接拒绝，不静默落默认值。"""
    text = str(value or "")
    values = tuple(allowed)
    if text not in values:
        raise ValueError(f"未知的{what}：{text!r}（应为 {values} 之一）")
    return text


